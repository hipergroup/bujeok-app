// 24절기 (二十四節氣) 천문 계산 모듈
// ------------------------------------------------------------
// 만세력(萬歲曆)의 핵심은 "절기(節氣)"다.
// 태양의 겉보기 황경(黃經, apparent ecliptic longitude)이
// 15°의 배수가 되는 순간이 곧 절기이며, 그 중 30° 간격의
// 12개 절(節)이 사주(四柱)의 월주(月柱)를 가르는 경계가 된다.
//
//   입춘(315°) → 인월(寅), 경칩(345°) → 묘월(卯), ...
//
// 또한 사주의 년주(年柱)는 양력 1월 1일이 아니라
// "입춘(立春)"을 기준으로 바뀐다.
//
// 계산은 Jean Meeus, "Astronomical Algorithms" (2nd ed.) 를 따르며
// 태양 황경은 VSOP87D(지구 헬리오센트릭 황경) 절단 급수를 사용한다.
// (1900~2100년 구간에서 실제 절기 시각과 오차 1분 이내)
//
// 모든 결과 시각은 한국표준시(KST = UTC+9) 기준이다.
// ============================================================

