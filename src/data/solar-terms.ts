// 5. 절기 시각 탐색
// ============================================================

/** 태양의 평균 이동 속도 (도/일) */
const SUN_DEG_PER_DAY = 0.9856473;

/**
 * 태양 황경이 targetLongitude 가 되는 순간의 율리우스일(JD, 세계시 UT 기준)
 *
 * 뉴턴법 반복: 목표 황경과의 차이를 태양의 일일 운행속도로 나눠 보정한다.
 * @param year 탐색 기준 연도 (해당 연도 1월 1일 이후 최초 도달 시각)
 * @param targetLongitude 목표 황경 (0~360)
 */
export function findSolarTermJD(year: number, targetLongitude: number): number {
  const target = ((targetLongitude % 360) + 360) % 360;

  // 1월 1일 태양 황경은 약 280°. 거기서부터 목표까지 남은 각도로 초기 추정.
  const jan1 = toJulianDayTime(year, 1, 1, 0, 0);
  const remain = ((((target - 280) % 360) + 360) % 360) / SUN_DEG_PER_DAY;
  const est = jan1 + remain;

  // UT → TT
  let jde = est + deltaT(year) / 86400;

  for (let i = 0; i < 30; i++) {
    const lon = sunLongitude(jde);
    // -180 ~ +180 범위의 각도 차
    const diff = (((target - lon + 540) % 360) - 180);
    if (Math.abs(diff) < 1e-9) break;
    jde += diff / SUN_DEG_PER_DAY;
  }

  // TT → UT
  return jde - deltaT(year) / 86400;
}

/** 절기 시각 캐시 (year*100+termIndex → SolarTermTime) */
const termCache = new Map<number, SolarTermTime>();

/**
 * 특정 해의 특정 절기 시각 (KST)
 *
 * @param year  사주 기준 연도. 입춘(index 0) ~ 대한(index 23) 의 한 사이클을 의미한다.
 *              소한(22)·대한(23)은 다음 해 1월에 들어오므로 결과의 year 는 year+1 이 된다.
 * @param termIndex 0=입춘, 1=우수, ... 23=대한
 */
export function getSolarTerm(year: number, termIndex: number): SolarTermTime {
  const idx = ((termIndex % 24) + 24) % 24;
  const key = year * 100 + idx;
  const cached = termCache.get(key);
  if (cached) return cached;

  const lon = termLongitude(idx);
  // 소한(285°)·대한(300°)은 이듬해 1월에 위치
  const calYear = lon >= 285 && lon < 315 ? year + 1 : year;

  const jdUT = findSolarTermJD(calYear, lon);
  const d = fromJulianDay(jdUT + KST_OFFSET); // KST 로 변환
  const result: SolarTermTime = {
    year: d.year,
    month: d.month,
    day: d.day,
    hour: d.hour,
    minute: d.minute,
  };
  termCache.set(key, result);
  return result;
}

/** 한 해(입춘~대한)의 24절기 전체 */
export function getSolarTermsOfYear(
  year: number
): { index: number; name: string; hanja: string; longitude: number; time: SolarTermTime }[] {
  const list: { index: number; name: string; hanja: string; longitude: number; time: SolarTermTime }[] = [];
  for (let i = 0; i < 24; i++) {
    list.push({
      index: i,
      name: SOLAR_TERM_NAMES[i],
      hanja: SOLAR_TERM_HANJA[i],
      longitude: termLongitude(i),
      time: getSolarTerm(year, i),
    });
  }
  return list;
}

/**
 * 입춘(立春) 시각 (KST) — 사주 년주(年柱)의 기준점
 * @param year 양력 연도
 * @returns 해당 연도 2월의 입춘 월/일/시/분
 */
export function getIpchun(year: number): {
  month: number;
  day: number;
  hour: number;
  minute: number;
} {
  const t = getSolarTerm(year, 0);
  return { month: t.month, day: t.day, hour: t.hour, minute: t.minute };
}

