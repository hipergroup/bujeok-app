/**
 * 주어진 KST 시각의 태양 겉보기 황경
 * (입력은 한국 표준시 기준의 양력 날짜/시각)
 */
export function sunLongitudeAtKST(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number = 0
): number {
  const jdKST = toJulianDayTime(year, month, day, hour, minute);
  const jdUT = jdKST - KST_OFFSET;
  const jde = jdUT + deltaT(year) / 86400; // UT → TT
  return sunLongitude(jde);
}

/**
 * 월지(月支) 인덱스 판정 — 만세력 월주 계산의 핵심
 *
 * 태양 황경이 어느 30° 구간(절기 구간)에 있는지로 결정한다.
 *   315°~345° → 인(2)  |  345°~ 15° → 묘(3)  |  15°~ 45° → 진(4)
 *    45°~ 75° → 사(5)  |   75°~105° → 오(6)  | 105°~135° → 미(7)
 *   135°~165° → 신(8)  |  165°~195° → 유(9)  | 195°~225° → 술(10)
 *   225°~255° → 해(11) |  255°~285° → 자(0)  | 285°~315° → 축(1)
 *
 * 즉 "절입일(節入日) 이전이면 전 달의 월지" 규칙과 정확히 동치이며,
 * 절입 시각(분 단위)까지 반영된다.
 *
 * @returns 지지 인덱스 0(자)~11(해)
 */
export function getMonthBranchIndex(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number = 0
): number {
  const lon = sunLongitudeAtKST(year, month, day, hour, minute);
  const sector = Math.floor(((((lon - 315) % 360) + 360) % 360) / 30); // 0=인월
  return (sector + 2) % 12;
}

/**
 * 사주 년도 판정 — 입춘(立春) 이전 출생이면 전년(前年)으로 본다.
 *
 * 예) 1990-01-20 생 → 1990년 입춘(2/4) 이전이므로 사주 년도는 1989(기사년)
 *
 * @returns 사주 기준 연도
 */
export function getSajuYear(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number = 0
): number {
  // 3월 이후는 무조건 입춘 이후
  if (month > 2) return year;
  // 1월은 무조건 입춘 이전 (입춘은 항상 2/3~2/5)
  if (month < 2) return year - 1;

  const ip = getIpchun(year);
  if (day > ip.day) return year;
  if (day < ip.day) return year - 1;
  // 같은 날이면 시각 비교
  return hour * 60 + minute >= ip.hour * 60 + ip.minute ? year : year - 1;
}

/**
 * 해당 시각이 속한 절(節)의 정보 (절기명 + 월지)
 */
export function getCurrentMajorTerm(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number = 0
): { name: string; hanja: string; longitude: number; branchIndex: number } {
  const branchIndex = getMonthBranchIndex(year, month, day, hour, minute);
  const found = MAJOR_TERMS.find((t) => t.branchIndex === branchIndex);
  return found ?? MAJOR_TERMS[0];
}
