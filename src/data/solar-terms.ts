// 4. 태양의 겉보기 황경 (Apparent Solar Longitude)
// ============================================================

/** VSOP87 급수 합산 */
function sumSeries(series: readonly (readonly number[])[], tau: number): number {
  let s = 0;
  for (let i = 0; i < series.length; i++) {
    const t = series[i];
    s += t[0] * Math.cos(t[1] + t[2] * tau);
  }
  return s;
}

/** 지구의 헬리오센트릭 황경 L (도) */
function earthLongitude(t: number): number {
  const tau = t / 10; // 천년 단위
  const series = [EARTH_L0, EARTH_L1, EARTH_L2, EARTH_L3, EARTH_L4];
  let v = 0;
  for (let i = series.length - 1; i >= 0; i--) {
    v = v * tau + sumSeries(series[i], tau);
  }
  return v / 1e8 / RAD; // 1e-8 rad → 도
}

/** 지구-태양 거리 R (AU) */
function earthRadius(t: number): number {
  const tau = t / 10;
  const series = [EARTH_R0, EARTH_R1, EARTH_R2];
  let v = 0;
  for (let i = series.length - 1; i >= 0; i--) {
    v = v * tau + sumSeries(series[i], tau);
  }
  return v / 1e8;
}

/** 황경 장동 Δψ (단위: 초각") */
export function nutationInLongitude(t: number): number {
  const d = (297.85036 + 445267.11148 * t - 0.0019142 * t * t + (t * t * t) / 189474) * RAD;
  const m = (357.52772 + 35999.05034 * t - 0.0001603 * t * t - (t * t * t) / 300000) * RAD;
  const mp = (134.96298 + 477198.867398 * t + 0.0086972 * t * t + (t * t * t) / 56250) * RAD;
  const f = (93.27191 + 483202.017538 * t - 0.0036825 * t * t + (t * t * t) / 327270) * RAD;
  const om = (125.04452 - 1934.136261 * t + 0.0020708 * t * t + (t * t * t) / 450000) * RAD;

  let dpsi = 0;
  for (let i = 0; i < NUTATION_TERMS.length; i++) {
    const x = NUTATION_TERMS[i];
    const arg = x[0] * d + x[1] * m + x[2] * mp + x[3] * f + x[4] * om;
    dpsi += (x[5] + x[6] * t) * Math.sin(arg);
  }
  return dpsi * 0.0001;
}

/**
 * 태양의 겉보기 황경 (0~360도)
 * @param jd 율리우스일 (역학시 TT 기준, JDE)
 *
 * 지구 헬리오센트릭 황경 + 180° 에
 * FK5 보정, 장동(nutation), 광행차(aberration)를 적용한다.
 */
export function sunLongitude(jd: number): number {
  const t = (jd - 2451545.0) / 36525;

  // 지구 황경 → 태양 기하 황경
  let theta = earthLongitude(t) + 180;

  // VSOP87 → FK5 좌표계 보정
  theta += -0.09033 * ARCSEC;

  // 장동 + 광행차 보정 → 겉보기 황경
  const r = earthRadius(t);
  const lambda = theta + nutationInLongitude(t) * ARCSEC - (20.4898 / r) * ARCSEC;

  return ((lambda % 360) + 360) % 360;
}

