/* ── 날짜 시드 ── */

function dateSeed(d: Date): number {
  const n =
    d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();
  // xorshift 한 번 돌려 분포를 섞는다
  let x = n ^ 0x5f356495;
  x ^= x << 13;
  x ^= x >>> 17;
  x ^= x << 5;
  return Math.abs(x);
}

/**
 * 오늘의 한 마디 — 부적함에서 하나가 말을 건다.
 * 하루 동안은 같은 부적·같은 문장이 유지된다.
 */
export function getDailyWord(
  collection: SavedTalisman[],
  date: Date = new Date()
): DailyWord {
  const seed = dateSeed(date);

  if (!collection.length) {
    return {
      talismanName: null,
      message: GENERIC_WORDS[seed % GENERIC_WORDS.length],
    };
  }

  const talisman = collection[seed % collection.length];
  const pool =
    WORDS_BY_CATEGORY[talisman.category] ?? WORDS_BY_CATEGORY['기타'];
  // 부적 선택과 문구 선택의 시드를 다르게 섞는다
  const message = pool[(seed >>> 3) % pool.length];

  return {
    talismanName: talisman.name,
    hanja: talisman.hanja,
    message,
  };
}
