/** 질문 문구를 변형 중에서 랜덤으로 하나 고른다 */
export function pickQuestion(step: ConsultStep): string {
  const pool = [step.question, ...(step.questionVariants ?? [])];
  return pool[Math.floor(Math.random() * pool.length)];
}

/** 선택지 답변에 대한 공감 리액션 (없으면 null) */
