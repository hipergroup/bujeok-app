/** 부적 카테고리 (문자열 값은 UI 표기와 동일) */
export enum TalismanCategory {
  Protection = '수호',
  Wealth = '재물',
  Health = '건강',
  Family = '가정',
  Study = '학업',
  Other = '기타',
  Love = '연애',
}

/** 부적 디자인 정보 — 전통 문양/글자 기록을 구조화한 값 */
export interface TalismanDesign {
  /** 부적 중앙에 크게 쓰는 글자 (예: 辟邪, 招福, 壽) */
  centerText: string;
  /** 장식 문양 (뇌문, 구름, 팔괘, 물결 등) */
  patterns: string[];
  /** 구상적 상징 요소 (동물, 신장, 도깨비 얼굴 등) */
  symbols: string[];
  /** 먹(안료) 색상 */
  inkColor: string;
  /** 바탕 종이 색상 */
  paperColor: string;
  /** 디자인 특이사항 / 배치 지침 */
  notes: string;
}

/** 부적 타입 */
export interface TalismanType {
  id: string;
  name: string;
  hanja: string;
  category: TalismanCategory;
  /** 카드 표시용 1~2문장 요약 */
  description: string;
  /** 상세 의미/용도 */
  meaning: string[];
  /** 사용 상황 */
  situations: string[];
  /** 문양/글자 등 디자인 정보 */
  design: TalismanDesign;
  /** 사용법 */
  usage: string[];
  /** 부착·소지 위치 */
  placement: string;
  /** 교체 주기 */
  replacement: string;
  /** 주문/진언 */
  mantra: string;
  /** UI용 색상 팔레트 [주사 붉은색, 황지 노란색, 카테고리 강조색] */
  colors: string[];
}

