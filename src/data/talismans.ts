/**
 * 카테고리 & 키워드 기반 부적 추천
 * 1) 키워드로 후보를 모으고 2) 카테고리로 필터링한 뒤
 * 3) 매칭 점수가 가장 높은 부적을 반환한다.
 */
export function getTalismanRecommendation(
  category: TalismanCategory | null,
  keywords: string[]
): TalismanType {
  // 1. 키워드 매칭으로 후보 수집
  const candidateIds = new Set<string>();
  for (const kw of keywords) {
    for (const [mapKey, ids] of Object.entries(KEYWORD_MAP)) {
      if (kw.includes(mapKey) || mapKey.includes(kw)) {
        ids.forEach((id) => candidateIds.add(id));
      }
    }
  }

  // 2. 카테고리 필터링
  let candidates = TALISMANS.filter((t) => candidateIds.has(t.id));
  if (category) {
    const categoryFiltered = candidates.filter((t) => t.category === category);
    if (categoryFiltered.length > 0) {
      candidates = categoryFiltered;
    }
  }

  // 3. 후보가 없으면 카테고리 기반 폴백
  if (candidates.length === 0) {
    if (category) {
      candidates = TALISMANS.filter((t) => t.category === category);
    }
    if (candidates.length === 0) {
      candidates = TALISMANS;
    }
  }

  // 4. 키워드 매칭 점수 기반 정렬
  const score = (t: TalismanType): number => {
    let s = 0;
    for (const kw of keywords) {
      if (t.name.includes(kw) || t.description.includes(kw)) s += 3;
      if (t.situations.some((sit) => sit.includes(kw))) s += 2;
      if (t.meaning.some((m) => m.includes(kw))) s += 1;
      for (const [mapKey, ids] of Object.entries(KEYWORD_MAP)) {
        if ((kw.includes(mapKey) || mapKey.includes(kw)) && ids.includes(t.id)) {
          s += 1;
        }
      }
    }
    return s;
  };

  // 동점이면 늘 카탈로그 앞쪽이 이겨 특정 부적(벽사부·재물부)에 쏠렸다.
  // 키워드+부적 id 로 정한 1 미만의 결정적 가중치로 동점만 가른다 —
  // 같은 답이면 언제나 같은 부적, 답이 다르면 동점끼리도 갈린다.
  const tieBreak = (t: TalismanType): number => {
    const str = keywords.join('|') + '::' + t.id;
    let h = 5381;
    for (let i = 0; i < str.length; i++) {
      h = ((h << 5) + h + str.charCodeAt(i)) >>> 0;
    }
    return (h % 997) / 997;
  };

  return [...candidates].sort(
    (a, b) => score(b) + tieBreak(b) - (score(a) + tieBreak(a))
  )[0];
}

/** 카테고리별 랜덤 부적 반환 */
export function getRandomTalisman(category?: TalismanCategory): TalismanType {
  let pool = TALISMANS;
  if (category) {
    pool = TALISMANS.filter((t) => t.category === category);
    if (pool.length === 0) pool = TALISMANS;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

/** 카테고리에 속한 부적 목록 반환 */
export function getTalismansByCategory(
  category: TalismanCategory
): TalismanType[] {
  return TALISMANS.filter((t) => t.category === category);
}

/** id로 부적 조회 */
export function getTalismanById(id: string): TalismanType | undefined {
  return TALISMANS.find((t) => t.id === id);
}
