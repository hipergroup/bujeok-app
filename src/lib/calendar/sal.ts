// ============================================================
// 살(煞) — 전통적으로 큰일을 피하는 날
//
// ⚠ 이 파일에는 "자료가 서로 일치해 확인된 것"만 넣는다.
//   기억이나 추측으로 표를 적지 않는다 — 틀린 표로 날짜를 물리게 하면
//   되돌리기 어려운 결정에 잘못된 근거를 주는 셈이기 때문이다.
//
// 지금 반영된 것
//   · 월기일(月忌日) — 음력 5·14·23일
//
// 아직 안 넣은 것 (표를 확인하지 못함)
//   · 고초일 · 대공망일 · 십악대패일 · 살부대기월
// ============================================================

/** 이 파일이 지금 반영하는 살 목록 — 화면에 "무엇까지 봤는지" 밝히는 데 쓴다 */
export const APPLIED_SAL = ['월기일'] as const;

/** 아직 반영하지 못한 살 — 화면에서 정직하게 알린다 */
export const PENDING_SAL = [
  '고초일',
  '대공망일',
  '십악대패일',
  '살부대기월',
] as const;

/**
 * 월기일(月忌日) — 음력 5·14·23일.
 * 한 달을 셋으로 나눈 각 구간의 다섯째 날로, 예부터 큰일을 벌이지 않는 날로 본다.
 */
export function isWolgiil(lunarDay: number): boolean {
  return lunarDay === 5 || lunarDay === 14 || lunarDay === 23;
}
